import assert from 'node:assert/strict';
import { buildBom, bomToCsv, isDnp, componentPopulation, normalizeMpn } from '../src/mcp-server/analyzers/bom';
import { evaluateFabRelease } from '../src/mcp-server/analyzers/fab-release';
assert.equal(isDnp({designator:'R1', otherProperties:{DNP:'no'}}),false);
assert.equal(isDnp({designator:'R1', otherProperties:{Place:'yes'}}),false);
assert.equal(isDnp({designator:'R1', otherProperties:{Place:'no'}}),true);
assert.equal(isDnp({designator:'R1', addIntoBom:false}),false);
assert.equal(componentPopulation({designator:'R1',otherProperties:{DNP:true,Place:true}}).population,'unknown');
assert.equal(normalizeMpn(' PARTCT '),'PARTCT');
const known={mpn:'TEST-TR',manufacturer:'A',footprint:'SOIC',value:'10k',otherProperties:{DNP:'no'}};
const report=buildBom({components:{a:{...known,designator:'R1'},b:{...known,designator:'R2'},c:{...known,designator:'R3',footprint:'TSSOP'},d:{designator:'C1',footprint:'0402'},e:{designator:'C2',footprint:'0402'},f:{...known,designator:'R4',addIntoBom:false}}});
assert.equal(report.rowCount,5);
assert.equal(report.rows.find(r=>r.designators.includes('R1'))?.qty,2);
assert.equal(report.excludedCount,1);
assert.equal(report.unknownPopulationCount,2);
assert.ok(report.rows.find(r=>r.designators.includes('R3'))?.conflicts.length);
const dnp=buildBom({components:{a:{...known,designator:'R1',otherProperties:{DNP:true}},b:{...known,designator:'R2',otherProperties:{DNP:true}}}});
assert.equal(dnp.rowCount,1);assert.equal(dnp.dnpCount,2);
const one=buildBom({components:{a:{...known,designator:'R1'}}});
const prior='Designators,Chosen_Distributor,Notes\r\nR1,chosen,"first line\nsecond, line"\r\n';
const csv=bomToCsv(one,{existingCsv:prior});
assert.ok(csv.includes('"first line\nsecond, line"'));
assert.equal(bomToCsv(one,{existingCsv:csv}),csv);
const formula=bomToCsv(buildBom({components:{a:{...known,designator:'=1+1'}}}));
assert.ok(formula.includes("'=1+1"));
const empty=evaluateFabRelease({});assert.equal(empty.pass,false);assert.equal(empty.status,'inconclusive');assert.ok(empty.coverage.every(c=>c.status==='not-run'));
const failed=evaluateFabRelease({bom:one,evidenceErrors:{pcbEmc:'extraction failed'}});
assert.equal(failed.pass,false);assert.equal(failed.status,'error');assert.ok(failed.checks.some(c=>c.detail==='extraction failed'));
assert.ok(!failed.summary.includes('OK to manufacture'));
console.log('BOM semantics and missing/error release evidence: passed.');
