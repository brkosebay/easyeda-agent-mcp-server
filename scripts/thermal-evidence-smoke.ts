import assert from 'node:assert/strict';
import { analyzeThermal, inferRailVoltage } from '../src/mcp-server/analyzers/thermal';
const unknown = analyzeThermal({components:{U1:{designator:'U1',deviceClass:'ic'}},nets:{}});
assert.equal(unknown.totalEstimatedWatts,null);
assert.deepEqual(unknown.hottest,[]);
assert.equal(unknown.coverage.unknownComponents,1);
assert.match(unknown.summary,/cannot be estimated/);
assert.doesNotMatch(unknown.summary,/0\.00W|Hottest/);
assert.equal(inferRailVoltage('VBAT'),null);
assert.equal(inferRailVoltage('VBUS'),null);
assert.equal(inferRailVoltage('12V'),12);
const partial = analyzeThermal({components:{R1:{designator:'R1',deviceClass:'resistor',value:'1k',pins:{1:{name:'1',net:'5V'},2:{name:'2',net:'GND'}}},U1:{designator:'U1',deviceClass:'ic'}},nets:{'5V':{name:'5V',isPower:true},GND:{name:'GND',isGround:true}}});
assert.equal(partial.totalEstimatedWatts,0.025);
assert.equal(partial.coverage.estimatedComponents,1);
assert.equal(partial.coverage.unknownComponents,1);
assert.match(partial.summary,/not total board/);
assert.equal(partial.hottest[0].designator,'R1');
assert.equal(partial.estimates.some(e=>e.designator==='U1'),true);
console.log('Thermal unknowns, partial coverage, small-power subtotal and ambiguous rail names: passed.');
